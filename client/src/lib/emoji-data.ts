export type Emoji = {
  /** The character(s). What is stored, sent and compared. */
  e: string;
  /** Short name, shown on hover and matched on. */
  n: string;
  /** Extra search terms. Matched on, never displayed. */
  k: string[];
  /** True when this glyph accepts a skin-tone modifier. */
  t?: boolean;
};

