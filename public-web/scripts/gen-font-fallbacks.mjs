#!/usr/bin/env node
/**
 * Generate `src/fonts-fallback.css` — the metric-matched fallback faces.
 *
 * ── THE DEFECT THIS CLOSES (guide O-12 / F-33) ────────────────────────────
 *
 * Every face is declared `font-display: swap`, for a reason `fonts.css` states
 * and still stands: "a headline that is invisible until a font arrives is a
 * worse first impression than one that reflows." What it did not account for is
 * what the reflow COSTS. Inter is about 15% wider than the `sans-serif` a
 * browser substitutes, so when it lands the text rewraps and everything below
 * it moves.
 *
 * Measured on `/about?lang=fr`: **CLS 0.184 and Lighthouse performance 87**,
 * against 0 and 95 for the identical page in English — French words are longer,
 * so the reflow is bigger. Lighthouse named the element (`footer.band-hero`)
 * and the cause ("Web font loaded"). It is pre-existing and app-wide;
 * `/careers?lang=fr` from PR 4 measures 0.096 the same way.
 *
 * ── HOW A FALLBACK STOPS COSTING ANYTHING ─────────────────────────────────
 *
 * Re-declare the local font the generic would have picked anyway, with
 * `size-adjust` so its em box matches the real face's advance width, and
 * ascent/descent/line-gap overrides so its line box matches too. The browser
 * then paints the fallback in exactly the space the webfont will occupy, and
 * the swap is invisible.
 *
 * ── WHY THIS IS GENERATED AND NOT TYPED ───────────────────────────────────
 *
 * The numbers are ratios between two fonts' real metrics. F-33 declined to
 * hardcode them for a good reason — a constant measured in one container and
 * applied to every visitor is the shape of change that looks right and is wrong
 * somewhere nobody can see. So nothing here is typed:
 *
 *   · OUR faces are read from the actual `.woff2` files in `node_modules`, so
 *     the output moves when @fontsource ships a new cut.
 *   · The FALLBACK metrics come from `FALLBACK_METRICS` below, and every entry
 *     is verified against a real font file by
 *     `tests/unit/font-fallback-metrics.test.js` wherever that file exists on
 *     the machine running it. Liberation Sans is metric-compatible with Arial
 *     BY DESIGN — same advance widths, same vertical metrics — and Arial is
 *     metric-compatible with Helvetica, so one measured file pins the numbers
 *     for Windows, macOS and Linux.
 *
 * ── AND WHAT IS DELIBERATELY NOT COVERED ──────────────────────────────────
 *
 * Android's `sans-serif` is Roboto, whose metrics differ from the Arial family
 * and whose file is not a dependency of this repo. Rather than quote numbers
 * from memory — the thing F-33 refused to do — no Roboto fallback is emitted.
 * An Android visitor gets today's behaviour, unchanged and no worse, and the
 * `local()` list simply does not match for them.
 *
 * Usage: node scripts/gen-font-fallbacks.mjs [--check]
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "src", "fonts-fallback.css");

const {
  FACES,
  FALLBACK_METRICS,
  TARGET,
  readFaceMetrics,
  overrides,
} = require(join(ROOT, "scripts", "font-metrics.cjs"));

function generate() {
  const { SITE_FONT_FAMILIES, siteFontFallback } = require(
    join(ROOT, "..", "packages", "shared", "design", "site-fonts.js"),
  );

  const blocks = [];
  for (const id of Object.keys(FACES)) {
    const face = readFaceMetrics(id);
    const fallback = FALLBACK_METRICS[TARGET[id]];
    const o = overrides(face, fallback);
    const src = fallback.locals.map((n) => `local("${n}")`).join(", ");
    blocks.push(
      `/* ${SITE_FONT_FAMILIES[id]} → ${fallback.locals[0]} and its metric family.\n` +
        `   size-adjust ${o.sizeAdjust} · ascent ${o.ascentOverride} · descent ${o.descentOverride} */\n` +
        `@font-face {\n` +
        `  font-family: "${siteFontFallback(id)}";\n` +
        `  src: ${src};\n` +
        `  size-adjust: ${o.sizeAdjust};\n` +
        `  ascent-override: ${o.ascentOverride};\n` +
        `  descent-override: ${o.descentOverride};\n` +
        `  line-gap-override: ${o.lineGapOverride};\n` +
        `}`,
    );
  }

  return (
    `/* GENERATED by scripts/gen-font-fallbacks.mjs — do not edit.\n` +
    ` *\n` +
    ` * Metric-matched fallbacks, so \`font-display: swap\` costs no layout shift\n` +
    ` * (guide O-12 / F-33). Every number is derived from the real font files;\n` +
    ` * run the generator after a @fontsource bump and commit what it writes.\n` +
    ` *\n` +
    ` * These declare NO download — \`local()\` re-declares a font the machine\n` +
    ` * already has, with overrides that make it occupy the webfont's space.\n` +
    ` */\n\n` +
    blocks.join("\n\n") +
    "\n"
  );
}

const css = generate();
if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== css) {
    console.error(
      "✗ src/fonts-fallback.css is out of date.\n\n" +
        "  Regenerate with: node scripts/gen-font-fallbacks.mjs\n",
    );
    process.exit(1);
  }
  console.log("✓ font fallbacks are in sync with the shipped font files.");
} else {
  writeFileSync(OUT, css);
  console.log(`✓ wrote ${OUT}`);
}

