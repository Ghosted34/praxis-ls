export const CATEGORY_ORDER: Exclude<EmojiCategory, "recent">[] = [
  "people", "nature", "food", "activity", "travel", "objects", "symbols", "flags",
];

/**
 * Search across every category.
 *
 * Prefix matches on the NAME rank above keyword matches, which is what makes
 * typing "th" reach 👍 (thumbs up) before 🌡️ (thermometer) — people type the
 * first letters of the thing they want, and a picker that rewards a substring
 * match anywhere puts the answer on the third row.
 */
export function searchEmoji(term: string, limit = 60): Emoji[] {
  const q = term.trim().toLowerCase();
  if (!q) return [];
  const exact: Emoji[] = [];
  const prefix: Emoji[] = [];
  const loose: Emoji[] = [];
  for (const category of CATEGORY_ORDER) {
    for (const item of EMOJI[category]) {
      const name = item.n.toLowerCase();
      if (name === q) exact.push(item);
      else if (name.startsWith(q)) prefix.push(item);
      else if (name.includes(q) || item.k.some((k) => k.toLowerCase().includes(q))) loose.push(item);
    }
  }
  return [...exact, ...prefix, ...loose].slice(0, limit);
}

/** Total count — used by the test that guards against a category being emptied
 *  by a bad merge. */
export const EMOJI_COUNT = CATEGORY_ORDER.reduce((n, c) => n + EMOJI[c].length, 0);
