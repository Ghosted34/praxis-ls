/**
 * The five Fitzpatrick modifiers, in the order every platform picker shows
 * them. Index 0 is "no modifier" and is the default — a default of anything
 * else picks a skin tone on the user's behalf, which is not ours to pick.
 */
export const SKIN_TONES = ["", "\u{1F3FB}", "\u{1F3FC}", "\u{1F3FD}", "\u{1F3FE}", "\u{1F3FF}"] as const;
export const SKIN_TONE_LABELS = [
  "Default", "Light", "Medium-light", "Medium", "Medium-dark", "Dark",
] as const;

/**
 * Apply a skin tone to a glyph that takes one.
 *
 * The modifier goes after the BASE code point, which for a multi-code-point
 * emoji is not the same as appending to the string: "👍" is one code point and
 * appends cleanly, while a ZWJ sequence would need the modifier inserted after
 * its first. Only single-code-point glyphs are marked `t: true` below, so the
 * simple form is correct for every one of them — and anything not marked comes
 * back untouched rather than mangled.
 */
export function withSkinTone(emoji: Emoji, toneIndex: number): string {
  const tone = SKIN_TONES[toneIndex] || "";
  if (!tone || !emoji.t) return emoji.e;
  return emoji.e + tone;
}

