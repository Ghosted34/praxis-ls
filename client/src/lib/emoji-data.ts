/**
 * The emoji set, self-hosted.
 *
 * ── WHY THIS FILE EXISTS RATHER THAN A CDN SCRIPT TAG ─────────────────────
 *
 * Every off-the-shelf picker (emoji-mart and friends) fetches its dataset from
 * a CDN at runtime, and three properties of this product make that the wrong
 * shape:
 *
 *   The client is an installed PWA. An operator on a Douala–Kribi corridor with
 *   no signal can still open a conversation and type; a picker that needs a
 *   network round-trip before it can draw a grid is a picker that is broken
 *   exactly when the rest of the app is not.
 *
 *   It is multi-tenant and white-label. A third-party request fires from the
 *   tenant's device carrying the tenant's referrer, which is a disclosure they
 *   did not agree to and cannot see.
 *
 *   The CSP in the artifact/app shell allow-lists specific hosts. A dataset
 *   fetch is not a script and would be blocked with no visible error — the
 *   picker would simply stay empty, on some machines and not others.
 *
 * ── AND WHY IT IS A LAZY CHUNK ────────────────────────────────────────────
 *
 * It is still ~30 KB of strings that most sessions never open. Everything here
 * is behind a dynamic `import()` from `emoji-picker.tsx`, so the cost lands on
 * the first person who clicks the smiley and on nobody else. Vite gives it its
 * own chunk because nothing in the eager graph imports it — keep it that way:
 * a static import from a component that renders on mount would silently pull
 * the whole set into the main bundle.
 *
 * ── NO IMAGES, ANYWHERE ───────────────────────────────────────────────────
 *
 * These are code points rendered by the platform's own font. Sprite sheets
 * would be another asset to ship, another thing to version, and would render a
 * Twemoji face next to the system faces the OS keyboard inserts — the same
 * emoji looking like two different emoji in the same bubble.
 */

