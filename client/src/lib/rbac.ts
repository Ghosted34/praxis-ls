export type Grant = {
  role_id: string;
  module_key: string;
  can_create: boolean;
  can_read: boolean;
  can_update: boolean;
  can_delete: boolean;
  can_approve: boolean;
  /** 12771 — export is a right over DATA; validate and disburse are the two
   *  decisions maker-checker most wants apart from "approve". */
  can_export: boolean;
  can_validate: boolean;
  can_disburse: boolean;
};

